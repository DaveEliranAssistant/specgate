import { validateScan } from './gate.mjs';
const SAFE=/^[A-Za-z][A-Za-z0-9_.-]{0,119}$/;
const VARIABLE=/^[A-Za-z][A-Za-z0-9_]{0,79}$/;
const FORBIDDEN=new Set(['__proto__','constructor','prototype']);
function keys(value, allowed){if(!value||typeof value!=='object'||Array.isArray(value)||Object.keys(value).some(k=>!allowed.includes(k)))throw new Error('Unexpected schema keys');}
function safePath(path){if(typeof path!=='string'||!/^\/(?:[A-Za-z0-9_/-]|\{\{[A-Za-z][A-Za-z0-9_]*\}\})+$/.test(path)||path.startsWith('//')||path.includes('//'))throw new Error('Unsafe request path');}
function safeValues(value, depth=0){
 if(depth>20)throw new Error('Scenario nesting limit');
 if(value&&typeof value==='object')for(const [k,v]of Object.entries(value)){if(FORBIDDEN.has(k)||/password|token|secret|authorization|api.?key/i.test(k))throw new Error('Inline credentials or unsafe object key refused');safeValues(v,depth+1);}
}
function matchRoute(route,method,path){
 if(route.method!==method)return false;
 const left=route.path.split('/'),right=path.split('/');return left.length===right.length&&left.every((part,i)=>part.startsWith(':')?/^(?:[A-Za-z0-9_-]+|\{\{[A-Za-z][A-Za-z0-9_]*\}\})$/.test(right[i]):part===right[i]);
}
function validateStep(step,scan,variables){
 keys(step,['method','path','body','auth','expected','extract']);safePath(step.path);
 if(!scan.routes.some(r=>matchRoute(r,step.method,step.path)))throw new Error('Scenario action has no discovered route');
 for(const [,name]of step.path.matchAll(/\{\{([A-Za-z][A-Za-z0-9_]*)\}\}/g))if(!variables.has(name))throw new Error('Extraction used before definition');
 if(step.auth){keys(step.auth,['bearerEnv']);if(!/^[A-Z][A-Z0-9_]{0,99}$/.test(step.auth.bearerEnv))throw new Error('Invalid credential environment reference');}
 safeValues(step.body);keys(step.expected,['status','bodyEquals','bodyMatch']);
 if(!Number.isInteger(step.expected.status)||step.expected.status<100||step.expected.status>599)throw new Error('Reviewed status assertion is required');
 if('bodyEquals'in step.expected&&'bodyMatch'in step.expected)throw new Error('Choose exact or subset body matching');
 if('bodyMatch'in step.expected&&(!step.expected.bodyMatch||typeof step.expected.bodyMatch!=='object'||Array.isArray(step.expected.bodyMatch)))throw new Error('bodyMatch must be an object');
 safeValues(step.expected);
 if(step.extract){keys(step.extract,Object.keys(step.extract));for(const [name,field]of Object.entries(step.extract)){if(!VARIABLE.test(name)||FORBIDDEN.has(name)||!VARIABLE.test(field)||FORBIDDEN.has(field)||variables.has(name))throw new Error('Invalid extraction');variables.add(name);}}
}
export function generateTests(doc,scan){
 validateScan(scan,{accepted:true});keys(doc,['schemaVersion','review','scenarios']);
 if(doc.schemaVersion!=='specgate.scenarios/1')throw new Error('Unsupported scenarios schema');
 keys(doc.review,['reference']);if(typeof doc.review.reference!=='string'||!doc.review.reference.trim()||doc.review.reference.length>1000)throw new Error('Reviewed requirement reference is required');
 if(!Array.isArray(doc.scenarios)||!doc.scenarios.length||doc.scenarios.length>500||JSON.stringify(doc).length>2097152)throw new Error('Scenario count/size limit');
 const ids=new Set();
 for(const scenario of doc.scenarios){
  keys(scenario,['id','classification','steps','cleanup']);
  if(!SAFE.test(scenario.id)||ids.has(scenario.id)||!['approved_requirement','accepted_regression_behavior'].includes(scenario.classification))throw new Error('Invalid scenario identity/classification');ids.add(scenario.id);
  if(!Array.isArray(scenario.steps)||!scenario.steps.length||scenario.steps.length>50||('cleanup'in scenario&&(!Array.isArray(scenario.cleanup)||scenario.cleanup.length>50)))throw new Error('Invalid scenario steps');
  const variables=new Set();for(const step of [...scenario.steps,...scenario.cleanup??[]])validateStep(step,scan,variables);
 }
 return [
  '// Generated by SpecGate code-first. Reviewed expectations are not inferred from implementation.',
  '// Trusted scenario input is required. Run only against an explicitly approved isolated loopback target.',
  "import { test, expect, request } from '@playwright/test';",
  `const input = ${JSON.stringify(doc)};`,
  `const sourceRoutes = ${JSON.stringify(scan.routes.map(r=>({method:r.method,path:r.path,file:r.file,line:r.line}))) };`,
  "test.describe.configure({ mode: 'serial' });",
  loopback.toString(),renderPath.toString(),runStep.toString(),
  `for (const scenario of input.scenarios) {
 test(scenario.id, async () => {
  test.setTimeout(120000);
  const baseURL = loopback(process.env.SPECGATE_BASE_URL);
  test.info().annotations.push({type:'requirement',description:input.review.reference});
  test.info().annotations.push({type:'classification',description:scenario.classification});
  test.info().annotations.push({type:'source',description:JSON.stringify(sourceRoutes)});
  const api = await request.newContext({baseURL, timeout:10000, ignoreHTTPSErrors:false});
  const variables = Object.create(null);
  try { for (const step of scenario.steps) await runStep(api, step, variables); }
  finally {
   try { for (const step of scenario.cleanup ?? []) await runStep(api, step, variables); }
   finally { await api.dispose(); }
  }
 });
}`,''].join('\n');
}
function loopback(value){
 if(typeof value!=='string'||!/^http:\/\/127\.0\.0\.1:[0-9]{1,5}\/?$/.test(value))throw new Error('SPECGATE_BASE_URL must be an explicit isolated http://127.0.0.1:PORT');
 const url=new URL(value);if(Number(url.port)<1||Number(url.port)>65535)throw new Error('Invalid loopback port');return url.origin;
}
function renderPath(path,variables){
 return path.replace(/\{\{([A-Za-z][A-Za-z0-9_]*)\}\}/g,(_match,name)=>{
  const value=variables[name];if((typeof value!=='string'&&typeof value!=='number')||!/^[A-Za-z0-9_-]{1,200}$/.test(String(value)))throw new Error('Unsafe or missing extracted path value');return encodeURIComponent(String(value));
 });
}
async function runStep(api,step,variables){
 const headers={};if(step.auth){const token=process.env[step.auth.bearerEnv];if(!token||/[\r\n]/.test(token))throw new Error('Missing or invalid test credential');headers.Authorization='Bearer '+token;}
 const response=await api.fetch(renderPath(step.path,variables),{method:step.method,data:step.body,headers,maxRedirects: 0,timeout:10000});
 expect(response.status(),'Reviewed HTTP status').toBe(step.expected.status);
 if('bodyEquals'in step.expected||'bodyMatch'in step.expected||step.extract){
  const body=await response.json();if('bodyEquals'in step.expected)expect(body,'Reviewed exact body').toEqual(step.expected.bodyEquals);if('bodyMatch'in step.expected)expect(body,'Reviewed subset body').toMatchObject(step.expected.bodyMatch);
  for(const [name,field]of Object.entries(step.extract??{})){if(!body||!Object.hasOwn(body,field))throw new Error('Missing extraction field');variables[name]=body[field];}
 }
 await response.dispose();
}
